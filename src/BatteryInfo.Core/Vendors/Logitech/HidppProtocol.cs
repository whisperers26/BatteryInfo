using BatteryInfo.Core.Model;

namespace BatteryInfo.Core.Vendors.Logitech;

/// <summary>HID++ feature ids this app looks up (docs/protocols/logitech.md §6, §7, §9).</summary>
public static class HidppFeature
{
    public const ushort Root = 0x0000;
    public const ushort FeatureSet = 0x0001;
    public const ushort DeviceFwInfo = 0x0003;
    public const ushort DeviceName = 0x0005;
    public const ushort BatteryStatus = 0x1000;
    public const ushort BatteryVoltage = 0x1001;
    public const ushort UnifiedBattery = 0x1004;
    public const ushort WirelessDeviceStatus = 0x1D4B;
    public const ushort AdcMeasurement = 0x1F20;
}

/// <summary>How a received report relates to an outstanding request.</summary>
public enum HidppMatchKind
{
    /// <summary>Not an answer to this request (someone else's reply, a notification, an event).</summary>
    None,
    Reply,

    /// <summary>A 0x8F error, usually generated by the receiver (device unknown, unreachable, HID++ 1.0 only).</summary>
    Hidpp10Error,

    /// <summary>A 0xFF error from a HID++ 2.0 device.</summary>
    Hidpp20Error,
}

public readonly record struct HidppMatch(HidppMatchKind Kind, byte ErrorCode = 0);

/// <param name="Index">Feature index on this device, 0 when the feature is not supported.</param>
public readonly record struct HidppFeatureInfo(byte Index, byte Flags, byte Version);

/// <summary>Receiver register B5 sub-register 03.</summary>
public readonly record struct HidppReceiverInfo(uint Serial, int MaxDevices);

/// <summary>Receiver register B5 sub-register 2n: the wireless product id and HID++ 1.0 device kind of a slot.</summary>
public readonly record struct HidppPairingInfo(ushort Wpid, byte Kind);

/// <summary>DEVICE_FW_INFO (0x0003) getDeviceInfo.</summary>
public readonly record struct HidppDeviceIds(uint UnitId, ushort? Wpid, ushort? UsbPid);

/// <summary>A decoded battery value. <see cref="Approximate"/> is set when the percent is derived from a voltage or a
/// coarse level rather than reported by the device.</summary>
public readonly record struct HidppBattery(int? Percent, ChargeState Charge, bool Approximate);

[Flags]
public enum UnifiedBatteryLevel : byte
{
    None = 0,
    Critical = 0x01,
    Low = 0x02,
    Good = 0x04,
    Full = 0x08,
}

/// <summary>0x1004 getCapabilities: r0 = supported levels, r1 = flags (bit1: state of charge supported).</summary>
public readonly record struct UnifiedBatteryCapabilities(byte SupportedLevels, byte Flags)
{
    public bool HasStateOfCharge => (Flags & 0x02) != 0;
}

/// <summary>0x1004 getStatus: r0 = state of charge, r1 = level, r2 = charging status.</summary>
public readonly record struct UnifiedBatteryStatus(int StateOfCharge, UnifiedBatteryLevel Level, byte ChargingStatus);

/// <summary>Builds and parses HID++ 1.0 and 2.0 frames (docs/protocols/logitech.md). Pure: no I/O.</summary>
public static class HidppProtocol
{
    public const byte ShortReportId = 0x10;
    public const byte LongReportId = 0x11;
    public const int ShortLength = 7;
    public const int LongLength = 20;

    /// <summary>Device index of the receiver itself, and of a device on its own cable.</summary>
    public const byte ReceiverIndex = 0xFF;

    public const byte GetRegister = 0x81;
    public const byte GetLongRegister = 0x83;
    public const byte Hidpp10ErrorId = 0x8F;
    public const byte Hidpp20ErrorId = 0xFF;
    public const byte ReceiverInfoRegister = 0xB5;
    public const byte ConnectionNotification = 0x41;

    // HID++ 1.0 error codes (0x8F reports).
    public const byte ErrorInvalidSubId = 0x01;
    public const byte ErrorConnectFail = 0x04;
    public const byte ErrorUnknownDevice = 0x08;
    public const byte ErrorResourceError = 0x09;

    // HID++ 2.0 error codes (0xFF reports).
    public const byte ErrorInvalidFeatureIndex = 0x06;
    public const byte ErrorBusy = 0x08;

    /// <summary>A short HID++ 2.0 request: <c>10 dev index (fn&lt;&lt;4|sw) p0 p1 p2</c>.</summary>
    public static byte[] FeatureRequest(byte deviceIndex, byte featureIndex, int function, byte softwareId,
        byte p0 = 0, byte p1 = 0, byte p2 = 0)
    {
        ArgumentOutOfRangeException.ThrowIfNegative(function);
        ArgumentOutOfRangeException.ThrowIfGreaterThan(function, 0x0F);
        return [ShortReportId, deviceIndex, featureIndex, Address(function, softwareId), p0, p1, p2];
    }

    /// <summary>IRoot getProtocolVersion (feature index 0, function 1) with a marker byte the reply echoes.</summary>
    public static byte[] Ping(byte deviceIndex, byte softwareId, byte mark) =>
        FeatureRequest(deviceIndex, 0x00, 1, softwareId, 0x00, 0x00, mark);

    /// <summary>IRoot getFeature (feature index 0, function 0).</summary>
    public static byte[] GetFeature(byte deviceIndex, ushort featureId, byte softwareId) =>
        FeatureRequest(deviceIndex, 0x00, 0, softwareId, (byte)(featureId >> 8), (byte)featureId);

    /// <summary>FEATURE_SET (0x0001) fn1 getFeatureId: which feature is at <paramref name="featureIndex"/>. Sent to
    /// the index FEATURE_SET itself was resolved at.</summary>
    public static byte[] GetFeatureId(byte deviceIndex, byte featureSetIndex, byte featureIndex, byte softwareId) =>
        FeatureRequest(deviceIndex, featureSetIndex, 1, softwareId, featureIndex);

    /// <summary>HID++ 1.0 GET_REGISTER (0x81).</summary>
    public static byte[] ReadRegister(byte deviceIndex, byte register) =>
        [ShortReportId, deviceIndex, GetRegister, register, 0x00, 0x00, 0x00];

    /// <summary>HID++ 1.0 GET_LONG_REGISTER (0x83) of the receiver info register B5.</summary>
    public static byte[] ReadReceiverInfo(byte subRegister) =>
        [ShortReportId, ReceiverIndex, GetLongRegister, ReceiverInfoRegister, subRegister, 0x00, 0x00];

    /// <summary>Whether <paramref name="report"/> answers <paramref name="request"/> (§8). Reports with another
    /// software id, device index, feature, function or ping mark are not ours.</summary>
    public static HidppMatch Match(ReadOnlySpan<byte> request, ReadOnlySpan<byte> report)
    {
        if (request.Length < ShortLength || report.Length < ShortLength) return default;
        var device = request[1];
        var subId = request[2];
        var address = request[3];
        if (report[1] != device) return default;

        if (report[0] == ShortReportId && report[2] == Hidpp10ErrorId && report[3] == subId && report[4] == address)
            return new HidppMatch(HidppMatchKind.Hidpp10Error, report[5]);

        if (subId < 0x80 && report[0] == LongReportId && report[2] == Hidpp20ErrorId && report[3] == subId && report[4] == address)
            return new HidppMatch(HidppMatchKind.Hidpp20Error, report[5]);

        if (report[2] != subId || report[3] != address) return default;
        if (subId == GetLongRegister && (report[0] != LongReportId || report[4] != request[4])) return default;
        if (IsPing(request) && report[6] != request[6]) return default;
        return new HidppMatch(HidppMatchKind.Reply);
    }

    public static (int Major, int Minor) ParsePingReply(ReadOnlySpan<byte> reply) => (reply[4], reply[5]);

    public static HidppFeatureInfo ParseFeatureInfo(ReadOnlySpan<byte> reply) => new(reply[4], reply[5], reply[6]);

    /// <summary>FEATURE_SET fn1 getFeatureId: r0..r1 = feature id (big-endian), r2 = type, r3 = version (§6).</summary>
    public static ushort ParseFeatureId(ReadOnlySpan<byte> reply) => (ushort)(reply[4] << 8 | reply[5]);

    /// <summary>B5/03: payload[1..4] = receiver serial, payload[6] = max devices (§4c). Payload starts at byte 4.</summary>
    public static HidppReceiverInfo ParseReceiverInfo(ReadOnlySpan<byte> reply) =>
        new(BigEndian32(reply[5..]), reply[10]);

    /// <summary>B5/2n: payload[3..4] = wpid (big-endian), payload[7] &amp; 0x0F = HID++ 1.0 kind (§4d).</summary>
    public static HidppPairingInfo ParsePairingInfo(ReadOnlySpan<byte> reply) =>
        new((ushort)(reply[7] << 8 | reply[8]), (byte)(reply[11] & 0x0F));

    /// <summary>B5/3n: payload[1..4] = device serial, equal to the device's unitId (§4d).</summary>
    public static uint ParseExtendedPairingSerial(ReadOnlySpan<byte> reply) => BigEndian32(reply[5..]);

    /// <summary>B5/4n: payload[1] = length, payload[2..] = ASCII (§4d).</summary>
    public static string ParseCodename(ReadOnlySpan<byte> reply)
    {
        var text = reply[6..];
        return DecodeName(text[..Math.Min(reply[5], text.Length)]);
    }

    /// <summary>0x0003 fn0: r1..r4 = unitId, r6 = transport bits, then 2-byte model ids for each set bit in the
    /// order btid 0x01, btleid 0x02, wpid 0x04, usbid 0x08 (§6).</summary>
    public static HidppDeviceIds ParseDeviceIds(ReadOnlySpan<byte> reply)
    {
        var transports = reply[10];
        var models = reply[11..17];
        ushort? wpid = null, usbPid = null;
        var offset = 0;
        foreach (var flag in (ReadOnlySpan<byte>)[0x01, 0x02, 0x04, 0x08])
        {
            if ((transports & flag) == 0) continue;
            if (offset + 2 > models.Length) break;
            var id = (ushort)(models[offset] << 8 | models[offset + 1]);
            if (flag == 0x04) wpid = id;
            if (flag == 0x08) usbPid = id;
            offset += 2;
        }
        return new HidppDeviceIds(BigEndian32(reply[5..]), wpid, usbPid);
    }

    /// <summary>0x0005 fn0: r0 = name length.</summary>
    public static int ParseNameLength(ReadOnlySpan<byte> reply) => reply[4];

    /// <summary>0x0005 fn1(offset): up to 16 name bytes starting at r0.</summary>
    public static ReadOnlySpan<byte> NameChunk(ReadOnlySpan<byte> reply, int remaining)
    {
        var data = reply[4..];
        return data[..Math.Clamp(remaining, 0, Math.Min(16, data.Length))];
    }

    /// <summary>0x0005 fn2: r0 = device type.</summary>
    public static byte ParseDeviceType(ReadOnlySpan<byte> reply) => reply[4];

    public static string DecodeName(ReadOnlySpan<byte> bytes)
    {
        var end = bytes.IndexOf((byte)0);
        return System.Text.Encoding.UTF8.GetString(end < 0 ? bytes : bytes[..end]).Trim();
    }

    /// <summary>0x0005 device type: 0 keyboard, 1 remote, 2 numpad, 3 mouse, 4 trackpad, 5 trackball, 6 presenter,
    /// 7 receiver.</summary>
    public static DeviceKind KindFromDeviceType(byte type) => type switch
    {
        0 or 2 => DeviceKind.Keyboard,
        3 or 4 or 5 => DeviceKind.Mouse,
        _ => DeviceKind.Other,
    };

    /// <summary>HID++ 1.0 device kind from the pairing register (1 keyboard, 2 mouse).</summary>
    public static DeviceKind KindFromPairingKind(byte kind) => kind switch
    {
        1 => DeviceKind.Keyboard,
        2 => DeviceKind.Mouse,
        _ => DeviceKind.Other,
    };

    /// <summary>Receiver notification 0x41 (§9): <c>10 dev 41 protocol info wpidLo wpidHi</c>; info bit 6 set means
    /// the link is NOT established.</summary>
    public static bool TryParseConnectionNotification(ReadOnlySpan<byte> report, out byte deviceIndex, out bool linkEstablished)
    {
        deviceIndex = 0;
        linkEstablished = false;
        if (report.Length < ShortLength || report[0] != ShortReportId || report[2] != ConnectionNotification) return false;
        deviceIndex = report[1];
        linkEstablished = (report[4] & 0x40) == 0;
        return true;
    }

    /// <summary>An unsolicited HID++ 2.0 feature event (§8): software id 0, not an error, not a receiver
    /// notification.</summary>
    public static bool TryParseFeatureEvent(ReadOnlySpan<byte> report, out byte deviceIndex, out byte featureIndex, out int eventNumber)
    {
        deviceIndex = featureIndex = 0;
        eventNumber = 0;
        if (report.Length < ShortLength || report[2] >= 0x80 || (report[3] & 0x0F) != 0) return false;
        if (report[0] == ShortReportId && report[2] >= 0x40) return false;
        deviceIndex = report[1];
        featureIndex = report[2];
        eventNumber = report[3] >> 4;
        return true;
    }

    /// <summary>WIRELESS_DEVICE_STATUS (0x1D4B) event 0 with status 1: the device reconnected (§9).</summary>
    public static bool IsReconnectEvent(ReadOnlySpan<byte> report, byte wirelessStatusIndex) =>
        wirelessStatusIndex != 0
        && TryParseFeatureEvent(report, out _, out var featureIndex, out var eventNumber)
        && featureIndex == wirelessStatusIndex && eventNumber == 0 && report[4] == 0x01;

    // Battery features (§7). Every decoder takes the whole reply report; r0 is byte 4.

    public static UnifiedBatteryCapabilities ParseUnifiedCapabilities(ReadOnlySpan<byte> reply) => new(reply[4], reply[5]);

    public static UnifiedBatteryStatus ParseUnifiedStatus(ReadOnlySpan<byte> reply) =>
        new(reply[4], (UnifiedBatteryLevel)reply[5], reply[6]);

    /// <summary>0x1004 charging status r2: 1, 2, 5 charging; 3 full; 4 error; 0 discharging; others invalid.</summary>
    public static ChargeState UnifiedCharge(byte status) => status switch
    {
        0 => ChargeState.Discharging,
        1 or 2 or 5 => ChargeState.Charging,
        3 => ChargeState.Full,
        4 => ChargeState.Fault,
        _ => ChargeState.Unknown,
    };

    /// <summary>0x1004 getStatus. Uses the state of charge when the device supports it, otherwise approximates the
    /// percent from the level. Without capabilities, a state of charge of 1-100 is trusted.</summary>
    public static HidppBattery DecodeUnifiedBattery(ReadOnlySpan<byte> reply, UnifiedBatteryCapabilities? capabilities)
    {
        var status = ParseUnifiedStatus(reply);
        var charge = UnifiedCharge(status.ChargingStatus);
        var useStateOfCharge = capabilities is { } caps ? caps.HasStateOfCharge : status.StateOfCharge is > 0 and <= 100;
        if (useStateOfCharge && status.StateOfCharge <= 100) return new HidppBattery(status.StateOfCharge, charge, false);

        var levels = status.Level & (UnifiedBatteryLevel)(capabilities?.SupportedLevels ?? 0x0F);
        return new HidppBattery(LevelPercent(levels), charge, true);
    }

    /// <summary>0x1000 getBatteryLevelStatus: r0 = level % (0 unknown), r2 = status.</summary>
    public static HidppBattery DecodeBatteryStatus(ReadOnlySpan<byte> reply)
    {
        var status = reply[6];
        var charge = status switch
        {
            0 => ChargeState.Discharging,
            1 or 2 or 4 => ChargeState.Charging,
            3 => ChargeState.Full,
            5 or 6 or 7 => ChargeState.Fault,
            _ => ChargeState.Unknown,
        };
        int? percent = status == 3 ? 100 : reply[4] is > 0 and <= 100 ? reply[4] : null;
        return new HidppBattery(percent, charge, false);
    }

    /// <summary>0x1001 getBatteryInfo: r0..r1 = millivolts, r2 = flags (bit7 external power, then low 3 bits:
    /// 0 charging, 1 full, 2 not charging).</summary>
    public static HidppBattery DecodeBatteryVoltage(ReadOnlySpan<byte> reply)
    {
        var flags = reply[6];
        var charge = (flags & 0x80) == 0
            ? ChargeState.Discharging
            : (flags & 0x07) switch
            {
                0 => ChargeState.Charging,
                1 => ChargeState.Full,
                2 => ChargeState.NotCharging,
                _ => ChargeState.Unknown,
            };
        return new HidppBattery(VoltageToPercent(Millivolts(reply)), charge, true);
    }

    /// <summary>0x1F20 fn0: r0..r1 = millivolts, r2 = flags. Null when flags bit0 is clear (device inactive).</summary>
    public static HidppBattery? DecodeAdcMeasurement(ReadOnlySpan<byte> reply)
    {
        var flags = reply[6];
        if ((flags & 0x01) == 0) return null;
        var charge = flags switch
        {
            0x01 => ChargeState.Discharging,
            0x03 => ChargeState.Charging,
            0x07 => ChargeState.Full,
            _ => ChargeState.Unknown,
        };
        return new HidppBattery(AdcVoltageToPercent(Millivolts(reply)), charge, true);
    }

    /// <summary>HID++ 1.0 register 0x0D: r0 = %, r2 &amp; 0xF0 = 0x30 discharging, 0x50 charging, 0x90 full.</summary>
    public static HidppBattery DecodeRegisterBatteryCharge(ReadOnlySpan<byte> reply)
    {
        var charge = (reply[6] & 0xF0) switch
        {
            0x30 => ChargeState.Discharging,
            0x50 => ChargeState.Charging,
            0x90 => ChargeState.Full,
            _ => ChargeState.Unknown,
        };
        return new HidppBattery(reply[4] <= 100 ? reply[4] : null, charge, false);
    }

    /// <summary>HID++ 1.0 register 0x07: r0 = level (7 full, 5 good, 3 low, 1 critical), r1 = charging bits.</summary>
    public static HidppBattery DecodeRegisterBatteryStatus(ReadOnlySpan<byte> reply)
    {
        int? percent = reply[4] switch
        {
            7 => 90,
            5 => 50,
            3 => 20,
            1 => 5,
            _ => null,
        };
        var charging = reply[5];
        var charge = charging == 0 ? ChargeState.Discharging
            : (charging & 0x21) == 0x21 ? ChargeState.Charging
            : (charging & 0x22) == 0x22 ? ChargeState.Full
            : ChargeState.Unknown;
        return new HidppBattery(percent, charge, true);
    }

    /// <summary>Linux kernel 0x1001 voltage curve: the first entry at or below the voltage gives 100 - index.</summary>
    public static int VoltageToPercent(int millivolts) => Lookup(VoltageTable, millivolts);

    /// <summary>Linux kernel 0x1F20 voltage curve.</summary>
    public static int AdcVoltageToPercent(int millivolts) => Lookup(AdcVoltageTable, millivolts);

    private static int? LevelPercent(UnifiedBatteryLevel levels) =>
        levels.HasFlag(UnifiedBatteryLevel.Full) ? 90
        : levels.HasFlag(UnifiedBatteryLevel.Good) ? 50
        : levels.HasFlag(UnifiedBatteryLevel.Low) ? 20
        : levels.HasFlag(UnifiedBatteryLevel.Critical) ? 5
        : null;

    private static int Millivolts(ReadOnlySpan<byte> reply) => reply[4] << 8 | reply[5];

    private static int Lookup(ReadOnlySpan<int> table, int millivolts)
    {
        for (var i = 0; i < table.Length; i++)
        {
            if (millivolts >= table[i]) return 100 - i;
        }
        return 0;
    }

